#!/usr/bin/env python3
"""Readiness: which notes can start, and which are waiting on which question.

The map already says *when* (the Schedule tab) and *who* (executor colours). It
does not say *what is blocking each piece* — that needs a note's open questions
joined to the note itself, which is two tabs and a cross-reference by eye.

This prints that join as markdown, for a terminal or a ticket. It is a VIEW:
regenerate it, never edit it, and never put a conclusion here that is not
derivable from the notes. Anything else belongs on the note it decides.

    python3 scripts/readiness.py <flow-dir> [> READINESS.md]
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_flow import load, number_items  # noqa: E402


def blockers(note):
    return [(q["ref"], q["text"]) for q in note["questions"] if not q["answered"]]


def brief(text, width=88):
    """First sentence, or a hard truncation — the table needs one line."""
    head = text.split("? ")[0]
    head = head + "?" if head is not text and not head.endswith("?") else head
    head = head.split(". ")[0].rstrip(".") if "?" not in head else head
    return head if len(head) <= width else head[: width - 1].rstrip() + "…"


def main(flow_dir):
    cfg, _kinds, notes = load(flow_dir)
    number_items(notes)

    scheduled = [n for n in notes if n["start"]]
    scheduled.sort(key=lambda n: (n["start"], n["length"]))
    ready = [n for n in scheduled if not blockers(n)]
    blocked = [n for n in scheduled if blockers(n)]

    unit = (cfg.get("timeline") or {}).get("unitLabel", "week")
    out = ["# Readiness — what can start, and what it waits on", ""]
    # The newest note's `updated`, not today's date. Stamping the calendar makes
    # every regeneration a diff even when nothing changed, so the file churns in
    # git for nothing; stamping the content makes the output a pure function of
    # the notes — byte-identical until a note actually moves.
    stamp = max((str(n.get("updated") or "") for n in notes), default="") or "an unstamped note set"
    out += [
        "Generated by `scripts/readiness.py` from notes as of %s. A **view** over" % stamp,
        "the notes, not a source: every decision lives on the note it decides.",
        "Regenerate rather than edit; if this and the notes disagree, the notes win.",
        "",
        "Question handles match the Open questions tab — quote them when answering.",
        "",
    ]

    def span(n):
        return "%d" % n["start"] if n["length"] == 1 else "%d-%d" % (
            n["start"], n["start"] + n["length"] - 1)

    out += ["## Can start with nothing decided", ""]
    if ready:
        out += ["| Piece | %ss | Executor |" % unit.title(), "|---|---|---|"]
        out += ["| **%s** | %s | %s |" % (n["node"], span(n), n["executor"] or "—")
                for n in ready]
    else:
        out += ["Nothing is fully unblocked."]
    out += [""]

    out += ["## Blocked on one or more answers", ""]
    if blocked:
        out += ["| Piece | %ss | Executor | Waiting on |" % unit.title(), "|---|---|---|---|"]
        for n in blocked:
            waits = " · ".join("**%s** %s" % (r, brief(t, 52)) for r, t in blockers(n))
            out += ["| %s | %s | %s | %s |" % (n["node"], span(n), n["executor"] or "—", waits)]
    else:
        out += ["Nothing is blocked."]
    out += [""]

    loose = [(q["ref"], q["text"], n) for n in notes if not n["start"]
             for q in n["questions"] if not q["answered"]]
    if loose:
        out += ["## Open, and on no piece's bar", "",
                "These belong to notes with no place on the timeline, so no bar reports them.",
                ""]
        out += ["- **%s** (%s) %s" % (r, n["node"], brief(t)) for r, t, n in loose]
        out += [""]

    total_open = sum(len(blockers(n)) for n in notes)
    out += ["---", "",
            "%d scheduled pieces · %d unblocked · %d blocked · %d open questions"
            % (len(scheduled), len(ready), len(blocked), total_open)]
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: readiness.py <flow-dir>")
    main(sys.argv[1])
